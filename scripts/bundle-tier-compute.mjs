// Bundles src/lib/tierCompute.js (+ its deps, date-fns included) into one
// self-contained ESM file the tier-snapshot edge function imports, so the
// server runs byte-for-byte the same tier logic as the Dashboard.
//
// Runs as part of `npm run build`; the output is committed. If you change any
// tier logic and build, the regenerated bundle shows up in the git diff —
// deploy tier-snapshot along with the frontend.
//
// `./supabase` (the browser client, reads import.meta.env) is stubbed: some
// deps import it for their async helpers, which tierCompute never calls.
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

const stubBrowserSupabase = {
  name: 'stub-browser-supabase',
  setup(b) {
    b.onResolve({ filter: /(^|\/)supabase(\.js)?$/ }, (args) =>
      args.importer.includes(`${path.sep}src${path.sep}`) && args.path.startsWith('.')
        ? { path: args.path, namespace: 'stub' }
        : undefined)
    b.onLoad({ filter: /.*/, namespace: 'stub' }, () => ({
      contents: 'export const supabase = null',
      loader: 'js',
    }))
  },
}

await build({
  entryPoints: [path.join(root, 'src/lib/tierCompute.js')],
  outfile: path.join(root, 'supabase/functions/_shared/tierCompute.bundle.js'),
  bundle: true,
  format: 'esm',
  platform: 'neutral',
  target: 'es2022',
  legalComments: 'none',
  banner: { js: '// GENERATED by scripts/bundle-tier-compute.mjs from src/lib/tierCompute.js — do not edit.' },
  plugins: [stubBrowserSupabase],
  logLevel: 'warning',
})
